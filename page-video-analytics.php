        <div class="container">
            <div class="eyebrow">FAQs</div>
            <h2>Video analytics <span class="gold">FAQs.</span></h2>
            <div class="faq-list">
                <details open="">
                    <summary>What is video analytics?</summary>
                    <p>Video analytics is software-based technology that analyses live or recorded video to identify defined objects, events, movements or patterns and turn them into structured information or alerts.</p>
                </details>
                <details>
                    <summary>What is CCTV video analytics?</summary>
                    <p>CCTV video analytics applies analytics to security-camera footage so a system can identify selected events or objects instead of relying only on recording and manual monitoring.</p>
                </details>
                <details>
                    <summary>What can video analytics detect?</summary>
                    <p>Depending on the selected platform, video analytics can detect people, vehicles, objects, intrusion, line crossing, loitering, crowd conditions, occupancy, movement and other configured events.</p>
                </details>
                <details>
                    <summary>What is AI video analytics?</summary>
                    <p>AI video analytics uses artificial-intelligence or machine-learning techniques to analyse video and identify selected objects, behaviours or patterns. Exact capabilities depend on the technology and configuration.</p>
                </details>
                <details>
                    <summary>Can video analytics work with existing CCTV?</summary>
                    <p>Sometimes. Compatibility depends on camera hardware, image quality, placement, VMS, processing architecture and the analytics required. An assessment should be completed before assuming an existing system can support a particular capability.</p>
                </details>
                <details>
                    <summary>Can video analytics reduce false alarms?</summary>
                    <p>It can help make event detection more targeted by classifying selected objects and applying rules, but no analytics system should be presented as eliminating false alarms. Camera design, scene conditions and configuration remain important.</p>
                </details>
                <details>
                    <summary>Can video analytics count people?</summary>
                    <p>Some platforms support people counting through compatible cameras or analytics software. Counting areas, direction, reporting and performance depend on the selected technology and site design.</p>
                </details>
                <details>
                    <summary>Can video analytics measure occupancy?</summary>
                    <p>Some systems can estimate occupancy in defined areas. Occupancy analytics should be treated as an information layer and not as a substitute for site-specific life-safety or regulatory capacity controls.</p>
                </details>
                <details>
                    <summary>Can video analytics detect vehicles?</summary>
                    <p>Yes, where supported. Vehicle detection and classification can be used for defined security or operational scenarios. Licence plate recognition is a related but more specialised capability.</p>
                </details>
                <details>
                    <summary>What is the difference between video analytics and CCTV?</summary>
                    <p>CCTV captures, transmits, records and displays video. Video analytics adds software-based interpretation to selected video feeds so defined events, objects or patterns can be detected and reported.</p>
                </details>
                <details>
                    <summary>Can video analytics integrate with access control and alarms?</summary>
                    <p>Where the selected platforms support the required integration, analytics events can be associated with access-control, alarm or other electronic-security events to provide broader operational context.</p>
                </details>
                <details>
                    <summary>Does video analytics require AI cameras?</summary>
                    <p>Not necessarily. Some analytics run on compatible cameras, while others run on servers, appliances or video-management platforms. The appropriate architecture depends on the required analytics and existing infrastructure.</p>
                </details>
                <details>
                    <summary>What is edge video analytics?</summary>
                    <p>Edge analytics processes video or analytics functions at or close to the camera/device. This can reduce the need to send all video to a central processing environment, but suitability depends on the camera and application.</p>
                </details>
                <details>
                    <summary>How much does video analytics cost in Australia?</summary>
                    <p>There is no meaningful single price. Cost depends on the number and type of cameras, analytics scenarios, processing architecture, software/licensing, storage, integrations, network requirements, installation and ongoing support.</p>
                </details>
                <details>
                    <summary>Can video analytics be used across multiple sites?</summary>
                    <p>Yes, where the selected platform and architecture support multi-site management and reporting. Multi-site design should consider bandwidth, central administration, user permissions, storage, analytics processing and support.</p>
                </details>
                <details>
                    <summary>Can video analytics be used for retail?</summary>
                    <p>Yes. Depending on the system, retail applications can include people counting, occupancy, movement/footfall analysis, queue awareness, selected loss-prevention analytics and faster video investigation.</p>
                </details>
                <details>
                    <summary>Can video analytics be used for warehouses and industrial sites?</summary>
                    <p>Yes. Common applications include perimeter/intrusion detection, restricted-zone monitoring, people/vehicle detection, after-hours activity and incident investigation.</p>
                </details>
                <details>
                    <summary>Is facial recognition the same as video analytics?</summary>
                    <p>No. Video analytics is a broad category. Facial recognition is one specialised application that can involve identifying or comparing faces and therefore introduces additional privacy and governance considerations.</p>
                </details>
                <details>
                    <summary>How does Advent design a video analytics solution?</summary>
                    <p>Advent should begin with the site and the business/security question, then assess existing CCTV and infrastructure, define required analytics, design the architecture, configure and validate the solution, and provide ongoing support where applicable.</p>
                </details>
