                    <div class="eyebrow">FAQs</div>
                    <h2>
                        Licence plate recognition — frequently asked
                        questions
                    </h2>
                </div>
            </div>
            <div class="faq-list">
                <details>
                    <summary>What does ANPR stand for?</summary>
                    <p>
                        ANPR stands for Automatic Number Plate
                        Recognition. It captures and recognises vehicle
                        number plates and turns the result into
                        structured event data.
                    </p>
                </details>
                <details>
                    <summary>
                        What is licence plate recognition?
                    </summary>
                    <p>
                        Licence Plate Recognition (LPR) uses cameras and
                        software to capture and recognise vehicle number
                        plates. ANPR is the common Australian industry
                        term for the same general technology.
                    </p>
                </details>
                <details>
                    <summary>
                        How does automatic number plate recognition
                        work?
                    </summary>
                    <p>
                        A suitable camera captures the vehicle and
                        plate, recognition software processes the image
                        and extracts the characters, and the resulting
                        event can then be recorded, searched, matched or
                        used for a configured action.
                    </p>
                </details>
                <details>
                    <summary>
                        What is the difference between an ANPR camera
                        and a CCTV camera?
                    </summary>
                    <p>
                        Standard CCTV is generally designed for
                        wider-area surveillance. ANPR capture is
                        designed around the plate read point, with
                        camera position, optics, distance, speed and
                        lighting selected for the required recognition
                        scenario.
                    </p>
                </details>
                <details>
                    <summary>Can ANPR open a boom gate?</summary>
                    <p>
                        It can where the selected ANPR, access-control
                        and boom-gate systems support the required
                        integration. A recognised authorised plate can
                        be used as an input to a configured access rule.
                    </p>
                </details>
                <details>
                    <summary>Can ANPR integrate with CCTV?</summary>
                    <p>
                        Yes, where the selected platforms support the
                        integration. ANPR can provide vehicle-event
                        information while CCTV provides broader visual
                        context and associated footage.
                    </p>
                </details>
                <details>
                    <summary>Does ANPR work at night?</summary>
                    <p>
                        Suitable ANPR systems can be designed for night
                        operation, but performance depends on camera
                        selection, infrared capability, vehicle speed,
                        lighting, angle, plate characteristics and scene
                        conditions.
                    </p>
                </details>
                <details>
                    <summary>How accurate is ANPR?</summary>
                    <p>
                        There is no single accuracy figure that applies
                        to every deployment. Performance depends on
                        technology, camera setup, vehicle speed, angle,
                        lighting, weather, plate condition and
                        configuration. Advent should validate the system
                        under representative site conditions.
                    </p>
                </details>
                <details>
                    <summary>
                        Can ANPR work across multiple lanes?
                    </summary>
                    <p>
                        Potentially. Multi-lane coverage depends on lane
                        geometry, vehicle speed, camera architecture and
                        required read performance. Some sites may
                        require multiple cameras or dedicated lane
                        capture.
                    </p>
                </details>
                <details>
                    <summary>
                        Can an existing CCTV system be upgraded with
                        ANPR?
                    </summary>
                    <p>
                        Sometimes. Compatibility depends on the cameras,
                        VMS, image quality, processing capability,
                        network, read-point geometry and required LPR
                        functionality. A site assessment should be
                        completed first.
                    </p>
                </details>
                <details>
                    <summary>
                        How much does a licence plate recognition system
                        cost?
                    </summary>
                    <p>
                        There is no useful single price. Cost depends on
                        lanes and cameras, camera/processing
                        requirements, integration, networking, storage,
                        software/licensing, installation and ongoing
                        support.
                    </p>
                </details>
                <details>
                    <summary>Can ANPR identify the driver?</summary>
                    <p>
                        Standard number plate recognition identifies the
                        vehicle plate, not necessarily the person
                        driving. Any separate driver or
                        facial-identification capability would be a
                        distinct technology with additional privacy and
                        governance considerations.
                    </p>
                </details>
