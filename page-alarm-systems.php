                        What is a commercial alarm system?
                    </summary>
                    <p>
                        A commercial alarm system is an electronic
                        security system designed to detect defined
                        events at a business or commercial site and
                        generate an alert. It commonly includes sensors,
                        a control panel, user interfaces and
                        communications equipment.
                    </p>
                </details>
                <details>
                    <summary>
                        What is the difference between an alarm system
                        and alarm monitoring?
                    </summary>
                    <p>
                        The alarm system is the on-site technology that
                        detects and reports configured events. Alarm
                        monitoring is an additional service in which
                        relevant events can be transmitted to a
                        monitoring service that follows an agreed
                        response process.
                    </p>
                </details>
                <details>
                    <summary>
                        How much does a commercial alarm system cost?
                    </summary>
                    <p>
                        There is no useful single price. Cost depends on
                        the site, protected zones, detection devices,
                        wiring or wireless requirements, control
                        equipment, communications, integrations,
                        installation complexity and whether monitoring
                        is included.
                    </p>
                </details>
                <details>
                    <summary>
                        Should I choose a wired or wireless alarm
                        system?
                    </summary>
                    <p>
                        It depends on the building, cabling access,
                        security requirements, environmental conditions
                        and future plans. Wired, wireless and hybrid
                        architectures can each be appropriate in
                        different circumstances.
                    </p>
                </details>
                <details>
                    <summary>
                        Can a business alarm system integrate with CCTV?
                    </summary>
                    <p>
                        Where the selected platforms support the
                        required integration, alarm events can be
                        associated with CCTV or video surveillance to
                        provide additional context around an event.
                    </p>
                </details>
                <details>
                    <summary>
                        Can an alarm system be monitored 24/7?
                    </summary>
                    <p>
                        Some commercial alarm systems can be connected
                        to 24/7 monitoring services. The exact
                        monitoring arrangement, response process and
                        service availability should be confirmed for the
                        proposed solution.
                    </p>
                </details>
                <details>
                    <summary>
                        What sensors are used in commercial alarm
                        systems?
                    </summary>
                    <p>
                        Depending on the site and design, systems may
                        use door and window contacts, motion detectors,
                        glass-break detection and other specialised
                        devices. Duress or panic devices may also be
                        appropriate in selected environments.
                    </p>
                </details>
                <details>
                    <summary>
                        Can Advent upgrade an existing alarm system?
                    </summary>
                    <p>
                        An existing system can be assessed for upgrade
                        or replacement. The decision depends on the
                        current control equipment, sensors,
                        communications, coverage, maintenance condition
                        and integration requirements.
                    </p>
                </details>
                <details>
                    <summary>
                        Do commercial alarm systems work after hours?
                    </summary>
                    <p>
