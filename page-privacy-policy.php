                    <section class="policy-section" id="policy-statement">
                        <span class="policy-section-number">01</span>
                        <div class="policy-section-body">
                            <h2>Policy Statement</h2>
                            <p>Advent Security is committed to managing personal information in an open and transparent way in accordance with the Privacy Act 1988 (Cth) and the Australian Privacy Principles (APPs).</p>
                            <p>This policy explains how we collect, hold, use, disclose and protect personal information relating to employees, clients, contractors, visitors, and other individuals who interact with our organisation.</p>
                        </div>
                    </section>

                    <section class="policy-section" id="scope">
                        <span class="policy-section-number">02</span>
                        <div class="policy-section-body">
                            <h2>Scope</h2>
                            <p>This policy applies to:</p>
                            <ul class="policy-list">
                                <li>All Advent Security employees and line managers</li>
                                <li>Visitors and clients</li>
                                <li>Contractors, subcontractors, and service providers</li>
                                <li>Any person whose personal information is handled by Advent Security in any form (digital, paper, CCTV, access systems, communications)</li>
                            </ul>
                        </div>
                    </section>

                    <section class="policy-section" id="definitions">
                        <span class="policy-section-number">03</span>
                        <div class="policy-section-body">
                            <h2>Definitions</h2>
                            <h3>Personal Information</h3>
                            <p>Information or an opinion about an identified individual, or an individual who is reasonably identifiable.</p>
                            <h3>Sensitive Information</h3>
                            <p>Includes health information, criminal history, biometric data, racial or ethnic origin, political opinions, membership of professional or trade associations, etc.</p>
                            <h3>Employee Records</h3>
                            <p>Records directly related to a current or former employment relationship. The Privacy Act includes an employee records exemption that may apply to certain acts and practices by a private sector employer in relation to employee records. Advent Security nevertheless aims to handle employee personal information in a consistent, careful and secure way.</p>
                            <div class="policy-callout">
                                <h3>3.1 Anonymity and Pseudonymity</h3>
                                <p>Where lawful and practicable, individuals may interact with Advent Security anonymously or by using a pseudonym.</p>
                                <p>However, anonymity or pseudonymity may not be possible where identification is required to:</p>
                                <ul class="policy-list">
                                    <li>provide security services</li>
                                    <li>comply with legal or regulatory obligations</li>
                                    <li>manage employment relationships</li>
                                    <li>conduct background checks or licensing verification</li>
                                    <li>investigate incidents or security events</li>
                                </ul>
                                <p>In such circumstances Advent Security may require sufficient information to verify the individual’s identity.</p>
                            </div>
                        </div>
                    </section>

                    <section class="policy-section" id="personal-information">
                        <span class="policy-section-number">04</span>
                        <div class="policy-section-body">
                            <h2>Types of Personal Information We Collect</h2>
                            <p>Depending on the individual and reason for interaction with Advent Security, we may collect:</p>
                            <h3>4.1 Employees, Contractors &amp; Applicants</h3>
                            <ul class="policy-list">
                                <li>Full name, date of birth, address, and contact details</li>
                                <li>Employment history, qualifications, licences, certificates</li>
                                <li>National Police Checks, Working With Children Checks</li>
                                <li>Health information relevant to fitness for work</li>
                                <li>Tax File Number (TFN) information is handled in accordance with the Privacy Act 1988 (Cth) and the Tax File Number Guidelines (as applicable), and is used only for authorised taxation, superannuation and payroll purposes.</li>
                                <li>Incident reports and investigation material</li>
                                <li>Site access logs, security clearance information</li>
                            </ul>
                            <p>Where we collect sensitive information (such as health information or criminal history information), we will do so only with the individual’s consent or where otherwise permitted or required by law (for example, to meet licensing, screening, work health and safety, or client contractual requirements).</p>
                            <h3>Government related identifiers</h3>
                            <p>We do not adopt, use or disclose government related identifiers (such as driver licence numbers or passport numbers) as our own identifier for individuals, except where required or authorised by law.</p>
                            <h3>4.2 Clients &amp; General Public</h3>
                            <ul class="policy-list">
                                <li>Contact details</li>
                                <li>CCTV footage</li>
                                <li>Access control logs</li>
                                <li>Incident and investigation information</li>
                                <li>Information provided when making enquiries</li>
                            </ul>
                        </div>
                    </section>

                    <section class="policy-section" id="collection">
                        <span class="policy-section-number">05</span>
                        <div class="policy-section-body">
                            <h2>How We Collect Personal Information</h2>
                            <p>We collect personal information in several ways:</p>
                            <ul class="policy-list">
                                <li>Directly from individuals through forms, interviews, onboarding, emails, phone calls</li>
                                <li>Through CCTV and security systems at controlled premises</li>
                                <li>Through electronic access systems and monitoring tools</li>
                                <li>From third-party service providers (e.g., Police Checks, training providers)</li>
                                <li>From publicly available sources where lawful and relevant</li>
                                <li>Through incident reporting and workplace inspection processes</li>
                            </ul>
                            <p>We will only collect information that is reasonably necessary for our business activities or to meet legal obligations.</p>
                            <h3>Unsolicited personal information</h3>
                            <p>If we receive personal information that we did not request, we will determine whether the information is reasonably necessary for our functions or activities. If it is not, we will, where lawful and reasonable, destroy or de-identify the information as soon as practicable.</p>
                            <h3>Collection notice</h3>
                            <p>At or before the time we collect personal information (or as soon as practicable afterwards) we will take reasonable steps to notify individuals of: the purpose of collection; the main consequences if information is not provided; the types of third parties we usually disclose to; whether we are likely to disclose information overseas (and, if practicable, the countries); and how individuals can access, correct and complain about the handling of their personal information.</p>
                            <div class="policy-callout">
                                <h3>CCTV and Security Monitoring</h3>
                                <p>Advent Security may operate CCTV and other security monitoring systems at sites where services are provided.</p>
                                <p>These systems are used for purposes including:</p>
                                <ul class="policy-list">
                                    <li>safety and security</li>
                                    <li>incident investigation</li>
                                    <li>access control and site monitoring</li>
                                    <li>compliance with client and regulatory requirements</li>
                                </ul>
                                <p>Where surveillance is conducted, appropriate signage is displayed in accordance with applicable legislation.</p>
                                <p>Access to CCTV footage (including copies) may be limited or refused where permitted by law—for example, where providing access would unreasonably impact the privacy of other individuals, prejudice an investigation, or disclose security-sensitive information.</p>
                            </div>
                        </div>
                    </section>

                    <section class="policy-section" id="purposes">
                        <span class="policy-section-number">06</span>
                        <div class="policy-section-body">
                            <h2>Purposes for Collecting, Using &amp; Disclosing Personal Information</h2>
                            <p>Advent Security uses and discloses personal information for the following purposes:</p>
                            <ul class="policy-list">
                                <li>Recruitment, onboarding, and workforce management</li>
                                <li>Compliance with legislative and regulatory requirements</li>
                                <li>Health &amp; safety management and incident investigation</li>
                                <li>Client contract fulfilment</li>
                                <li>Payroll administration and HR management</li>
                                <li>Training, competency verification, and licensing</li>
                                <li>Security monitoring, access control, and emergency response</li>
                                <li>Communication with clients and stakeholders</li>
                                <li>Risk management, insurance and legal processes</li>
                                <li>Maintaining operational records and service quality</li>
                            </ul>
                            <p>We do not sell or provide personal information for marketing purposes.</p>
                            <div class="policy-callout">
                                <h3>6.1 Direct Marketing</h3>
                                <p>Advent Security does not use personal information for direct marketing purposes and does not sell personal information to third parties.</p>
                                <p>If Advent Security ever intends to use personal information for marketing communications, individuals will be given the opportunity to opt out of receiving such communications.</p>
                            </div>
                        </div>
                    </section>

                    <section class="policy-section" id="third-parties">
                        <span class="policy-section-number">07</span>
                        <div class="policy-section-body">
                            <h2>Disclosure to Third Parties</h2>
                            <p>We may disclose personal information to:</p>
                            <ul class="policy-list">
                                <li>Government and law enforcement agencies</li>
                                <li>Licensing and regulatory bodies</li>
                                <li>External auditors and compliance assessors</li>
                                <li>Insurers, legal advisers, and investigators</li>
                                <li>Payroll, HR, and IT service providers</li>
                                <li>Clients, where required for operational or security purposes</li>
                            </ul>
                            <p>All disclosures are limited to what is lawful, necessary, and reasonable for business or legal purposes.</p>
                        </div>
                    </section>

                    <section class="policy-section" id="overseas-disclosure">
                        <span class="policy-section-number">08</span>
                        <div class="policy-section-body">
                            <h2>Overseas Disclosure</h2>
                            <p>Some service providers (e.g., cloud hosting, email systems, HR platforms) may store or process personal information outside Australia.</p>
                            <p>This may include, for example, the United States, United Kingdom or Singapore (noting that locations may change depending on providers and services used). Where personal information is disclosed overseas, Advent Security will take reasonable steps to ensure the disclosure is handled consistently with the Privacy Act and the APPs (including through due diligence and appropriate contractual and security measures), unless an exception under the Privacy Act applies.</p>
                            <ul class="policy-list">
                                <li>we conduct due diligence on overseas providers and their security practices</li>
                                <li>contractual and technical measures are in place to protect the information</li>
                                <li>Only the minimum required information is transferred</li>
                            </ul>
                        </div>
                    </section>

                    <section class="policy-section" id="security">
                        <span class="policy-section-number">09</span>
                        <div class="policy-section-body">
                            <h2>Security of Personal Information</h2>
                            <p>Advent Security takes all reasonable steps to secure personal information from misuse, loss, unauthorised access, modification, and disclosure.</p>
                            <p>Controls include:</p>
                            <ul class="policy-list">
                                <li>Role-based access restrictions</li>
                                <li>Encryption of information in transit and at rest</li>
                                <li>Multi-factor authentication for key systems</li>
                                <li>Secure storage for physical documents</li>
                                <li>CCTV monitoring and restricted areas</li>
                                <li>Regular audits and access reviews</li>
                                <li>Employee confidentiality obligations</li>
                                <li>Secure destruction of records when no longer required</li>
                            </ul>
                        </div>
                    </section>

                    <section class="policy-section" id="data-breach">
                        <span class="policy-section-number">09.1</span>
                        <div class="policy-section-body">
                            <h2>Data Breach Notification</h2>
                            <p>Advent Security complies with the Notifiable Data Breaches Scheme under the Privacy Act 1988 (Cth).</p>
                            <p>If a data breach occurs that is likely to result in serious harm to an individual, Advent Security will:</p>
                            <ul class="policy-list">
                                <li>promptly assess the breach (including completing any required assessment within 30 days)</li>
                                <li>take steps to contain and mitigate the incident</li>
                                <li>notify affected individuals where required</li>
                                <li>notify the Office of the Australian Information Commissioner (OAIC)</li>
                            </ul>
                            <p>Incident management procedures are implemented to ensure data breaches are identified, assessed and reported in accordance with legal requirements.</p>
                        </div>
                    </section>

                    <section class="policy-section" id="access-correction">
                        <span class="policy-section-number">10</span>
                        <div class="policy-section-body">
                            <h2>Access and Correction</h2>
                            <p>Individuals may request access to or correction of personal information held about them.</p>
                            <p>Requests must be made to the Privacy Officer using the contact details provided in this policy. We may ask for further information to verify identity and to help us locate the relevant information.</p>
                            <p>Advent Security will:</p>
                            <ul class="policy-list">
                                <li>verify the identity of the individual making the request</li>
                                <li>respond within a reasonable timeframe</li>
                                <li>provide access unless an exception under the Privacy Act applies</li>
                                <li>correct inaccurate, incomplete or outdated information where appropriate</li>
                            </ul>
                            <p>Access will generally be provided free of charge; however, we may charge a reasonable fee to cover the cost of providing access where permitted by law. We will respond within a reasonable timeframe and, where we refuse access or correction, we will provide reasons (where required) and information about complaint options.</p>
                            <p>Access may be refused where permitted by law, including where providing access would:</p>
                            <ul class="policy-list">
                                <li>pose a serious threat to health or safety</li>
                                <li>prejudice law enforcement activities</li>
                                <li>reveal commercially sensitive or security sensitive information</li>
                                <li>breach legal privilege</li>
                            </ul>
                            <p>Where access is refused, written reasons will be provided where required.</p>
                            <div class="policy-callout">
                                <h3>Retention and Destruction of Personal Information</h3>
                                <p>Advent Security retains personal information only for as long as necessary to fulfil the purposes for which it was collected, including legal, contractual, regulatory and operational requirements.</p>
                                <p>When personal information is no longer required it will be securely destroyed or permanently de-identified in accordance with organisational procedures and applicable records management requirements.</p>
                            </div>
                        </div>
                    </section>

