            <div class="boom-faq">

                <details>
                    <summary>What is a boom gate?</summary>

                    <div class="boom-answer">
                        A boom gate is a physical vehicle barrier with a
                        horizontal arm that controls passage through an
                        entry or exit lane. It can be operated by a
                        compatible access-control, detection or
                        vehicle-management system.
                    </div>
                </details>

                <details>
                    <summary>
                        Where are boom gates commonly used?
                    </summary>

                    <div class="boom-answer">
                        They are commonly used at commercial car parks,
                        office buildings, warehouses, logistics
                        facilities, industrial sites, service yards,
                        construction sites and other properties where
                        vehicle movement needs to be controlled.
                    </div>
                </details>

                <details>
                    <summary>
                        How does an automatic boom gate work?
                    </summary>

                    <div class="boom-answer">
                        A compatible control system receives an opening
                        request or detects the relevant vehicle
                        condition, checks the configured rule and raises
                        the barrier. Detection and programmed logic then
                        determine when the barrier can close.
                    </div>
                </details>

                <details>
                    <summary>
                        Can a boom gate integrate with access control?
                    </summary>

                    <div class="boom-answer">
                        Yes, where the selected systems support the
                        required connection. Card and mobile
                        credentials, keypads, intercoms and other
                        compatible access methods can be used to control
                        the opening command.
                    </div>
                </details>

                <details>
                    <summary>
                        Can a boom gate integrate with CCTV?
                    </summary>

                    <div class="boom-answer">
                        Yes. CCTV can provide visibility of the entry
                        and exit area and, where the platforms support
                        it, can form part of a broader
                        electronic-security workflow.
                    </div>
                </details>

                <details>
                    <summary>
                        Can an existing boom gate be upgraded?
                    </summary>

                    <div class="boom-answer">
                        Often, yes. An assessment can determine whether
                        the existing barrier, operator, controls and
                        associated infrastructure can be retained while
                        newer access or security technology is
                        introduced.
                    </div>
                </details>

                <details>
                    <summary>
                        What affects the cost of boom gate installation?
                    </summary>

                    <div class="boom-answer">
