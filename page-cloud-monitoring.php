        <div class="container">
            <div class="faq-head">
                <div>
                    <div class="eyebrow">FAQs</div>
                    <h2>Cloud security monitoring FAQs</h2>
                </div>
            </div>
            <div class="faq-list">
                <details>
                    <summary>
                        What is cloud monitoring in security?
                    </summary>
                    <p>
                        Cloud monitoring uses a cloud-connected platform
                        to access and manage information from supported
                        security systems. Depending on the solution,
                        this can include CCTV, video analytics, access
                        control and alarm events.
                    </p>
                </details>
                <details>
                    <summary>What is cloud CCTV?</summary>
                    <p>
                        Cloud CCTV uses cloud services for functions
                        such as remote access, management, storage,
                        analytics or video management. The exact setup
                        varies between platforms.
                    </p>
                </details>
                <details>
                    <summary>Can I access my CCTV remotely?</summary>
                    <p>
                        Many modern systems support remote access to
                        live or recorded footage. The available
                        functions depend on the cameras, VMS or cloud
                        platform, network and user permissions.
                    </p>
                </details>
                <details>
                    <summary>Is cloud CCTV better than an NVR?</summary>
                    <p>
                        Not automatically. Cloud, local NVR and hybrid
                        systems all have their place. The right choice
                        depends on connectivity, storage, resilience, IT
                        requirements and the way the site needs to
                        operate.
                    </p>
                </details>
                <details>
                    <summary>
                        Can I move an existing CCTV system to the cloud?
                    </summary>
                    <p>
                        Sometimes. Compatibility depends on the cameras,
                        recorder or VMS, network, image quality,
                        supported interfaces and selected cloud
                        platform. Advent should assess the existing
                        system before promising an upgrade path.
                    </p>
                </details>
                <details>
                    <summary>
                        Does cloud monitoring require an internet
                        connection?
                    </summary>
                    <p>
                        Cloud-connected systems generally require
                        network connectivity for remote cloud functions.
                        Some architectures include local recording or
                        buffering so selected functions can continue
                        during an internet interruption.
                    </p>
                </details>
                <details>
                    <summary>
                        Can cloud monitoring work across multiple sites?
                    </summary>
                    <p>
                        Yes, where the selected platform supports
                        multi-site management. This can allow authorised
                        users to access and administer multiple
                        locations from a central interface.
                    </p>
                </details>
                <details>
                    <summary>
                        Can cloud monitoring integrate with access
                        control?
                    </summary>
                    <p>
                        It can where the selected platforms support the
                        required integration. This may allow authorised
                        users to associate access events with CCTV or
                        manage selected access functions remotely.
                    </p>
                </details>
                <details>
                    <summary>
                        Can cloud monitoring integrate with alarm
                        systems?
                    </summary>
                    <p>
                        It can where compatible technologies support the
                        required integration. Cloud connectivity can
                        provide remote access to selected alarm
                        information, while professional Alarm Monitoring
                        remains a separate service.
                    </p>
                </details>
                <details>
                    <summary>
                        Is cloud monitoring the same as 24/7 alarm
                        monitoring?
                    </summary>
                    <p>
                        No. Cloud Monitoring provides cloud-enabled
                        access and management of security information.
                        Professional Alarm Monitoring involves trained
                        monitoring-centre operators assessing alarm
                        events and following defined response
                        procedures.
                    </p>
                </details>
                <details>
                    <summary>
                        Can cloud monitoring include video analytics?
                    </summary>
                    <p>
                        Yes, where the selected cloud or video platform
                        supports analytics. Capabilities depend on the
                        cameras, processing architecture, software and
                        licensing.
                    </p>
                </details>
                <details>
                    <summary>
                        Can cloud monitoring reduce the need for on-site
                        servers?
                    </summary>
                    <p>
                        Some cloud architectures reduce or remove
                        certain local server or recorder requirements,
                        but this is not universal. Hybrid architectures
                        may still retain local recording or processing.
                    </p>
                </details>
                <details>
                    <summary>Is cloud CCTV secure?</summary>
                    <p>
                        Security depends on the complete architecture,
                        including cameras, accounts, network, cloud
                        provider, authentication, permissions, software
                        and operational practices. A cloud platform
                        should not be described as secure by default.
                    </p>
                </details>
                <details>
                    <summary>
                        Where is cloud CCTV footage stored?
                    </summary>
                    <p>
                        The answer depends on the selected platform and
                        service provider. Storage location,
                        data-handling arrangements and retention should
                        be confirmed before deployment.
                    </p>
                </details>
                <details>
                    <summary>
                        How much does cloud monitoring cost in
                        Australia?
                    </summary>
                    <p>
                        There is no single price. Cost depends on
                        cameras or devices, sites, architecture,
                        storage, software or licensing, integrations,
                        connectivity, installation and support.
                    </p>
                </details>
